#!/usr/bin/env node
/**
 * commit-msg hook — enforces Conventional Commits format:
 *
 *   <type>(<scope>): <subject>
 *
 *   e.g. feat(agent): add white-box memory editor
 *        fix: correct token counting on streaming responses
 *
 * Types: feat | fix | docs | refactor | test | chore | style | perf | ci | build | revert | release
 */
import { readFileSync } from "node:fs";

const message = readFileSync(process.argv[2], "utf8").trim();
const CONVENTIONAL_RE = /^(feat|fix|docs|refactor|test|chore|style|perf|ci|build|revert|release)(\([\w-]+\))?!?: .+/;

// Merge and revert commits generated by git/GitHub are exempt.
if (/^(Merge|Revert) /.test(message)) process.exit(0);

if (!CONVENTIONAL_RE.test(message)) {
  console.error("✖ Invalid commit message format.");
  console.error("  Expected: <type>(<scope>): <subject>");
  console.error("  Example:  feat(agent): add white-box memory editor");
  console.error("  Types:    feat, fix, docs, refactor, test, chore, style, perf, ci, build, revert, release");
  process.exit(1);
}
