#!/usr/bin/env node
/**
 * Bootstrap ~/.sati/sati.yaml when it doesn't exist yet, so the
 * gateway can boot and the Web UI can run the onboarding flow that fills in
 * real provider details. Bundled skills are loaded directly from the active
 * Sati release and are intentionally not copied into user storage.
 *
 * Behaviour:
 *   1. Every run: if sati.yaml exists but is missing known sections
 *      (e.g. adapters), append the default snippet so new features are
 *      discoverable without requiring users to recreate the config.
 *   2. If $SATI_HOME/sati.yaml does not exist, write a minimal V2 yaml that:
 *        - has a valid agent.model that resolves to a catalog provider/model,
 *          so the engine's parseModelConfig won't crash on startup
 *        - uses a sentinel apiKey ("PLACEHOLDER_RUN_ONBOARDING_TO_REPLACE")
 *          that hasUsableSatiConfig() recognises as "not ready" so the
 *          UI redirects to onboarding instead of pretending it's configured.
 *
 * Override the target via $SATI_HOME (same env var the engine reads).
 * Skip the whole step via $SATI_SKIP_BOOTSTRAP=1.
 */
import { appendFileSync, copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";

