/**
 * UI 延时注册表 —— 集中存放 `setTimeout` / `setInterval` 的延时取值。
 *
 * ⚠️ **这是一张注册表，不是一堆魔法数字的别名**：改任何一项的值前，先想清有没有用户可见影响。
 * 这里的每个数字都落在行为面上——滚动落点、防抖手感、轮询频率/请求量、反馈时长、心跳节奏——
 * 调大调小都会改变交互观感或后端负载，属于行为变更而非重构；只在确有必要时改，并在 PR 里说明。
 *
 * 命名与使用约定：
 * - 名字说「在等什么」，不说「等多久」：`COPY_FEEDBACK_RESET_MS`，不要 `TIMEOUT_2000` / `DELAY_300`。
 * - 只有**语义相同**才共用同一个键；数值相同但语义不同必须各占一键，否则改一处会误动另一处。
 * - `NEXT_TASK_MS` 的 0 不是「没有等待」，而是「让出到下一个宏任务」（见该键注释）。
 * - 单位一律毫秒，键名以 `_MS` 结尾；对象用 `as const` 保持字面量类型，调用点无需额外断言。
 */
export const UI_TIMEOUTS = {
  // ===== 通用调度 =====

  /**
   * 让出到下一个宏任务：0 不是「没有等待」，而是把回调推迟到当前这一轮同步代码/微任务之后，
   * 让浏览器（或 React）先完成本次提交——新输入值进入 DOM、首屏渲染让位、rAF 已跑过。
   * 改成任何正数都会让这些「先落地再执行」的路径出现肉眼可见的延迟，故保持 0。
   */
  NEXT_TASK_MS: 0,

  // ===== 会话消息列表：渲染沉降后定位滚动（chat / chat-v2）=====

  /**
   * 自己发出消息（新发、重发、编辑最后一条）后，等新消息行完成一次布局再滚到底。
   * 100ms 是一个提交周期量级：太短会滚到旧高度（消息行还没进 DOM），太长用户能看到「先停后跳」。
   */
  CHAT_SEND_SCROLL_SETTLE_MS: 100,

  /**
   * 会话加载完成 / 外部刷新（WebSocket 重连、后台刷新）后，等消息列表重排完再滚到底。
   * 比发送路径（100ms）长一档：这里整列表都被替换，布局工作量更大，200ms 才稳定拿到新高度。
   */
  CHAT_RELOAD_SCROLL_SETTLE_MS: 200,

  /**
   * 「加载全部消息」拉回整段历史后，等这批消息渲染完再做滚动定位/高亮。
   * 300ms 对应「整会话一次性入 DOM」的量级，比单次刷新更重，故比 CHAT_RELOAD_SCROLL_SETTLE_MS 再长一档。
   */
  CHAT_FULL_LOAD_RENDER_SETTLE_MS: 300,

  /**
   * Fork 出新会话后：消息是会话切换后异步到达的，等这批随行历史渲染出来再补一次滚到底
   * （切会话时已先 rAF 滚过一次）。400ms 覆盖一次跨会话取数 + 首屏渲染。
   */
  CHAT_FORK_SCROLL_AFTER_RENDER_MS: 400,

  /**
   * 历史搜索前触发「加载全部消息」后，等消息落进 DOM 再开始扫 DOM 找命中项。
   * 350ms 是一次全量取数后渲染的保守等待；等待期间用户看不到搜索过程，故不宜再放大。
   */
  HISTORY_SEARCH_FULL_LOAD_WAIT_MS: 350,

  /**
   * 跳转到历史搜索命中项前，先等面板/列表打开的动画与首次布局起步。
   * 150ms 是「DOM 已经开始但还没画完」的窗口，之后进入重试循环逐次找目标元素。
   */
  SEARCH_SCROLL_INITIAL_DELAY_MS: 150,

  /**
   * 搜索定位找不到目标元素时的重试间隔（最多重试若干次，等消息陆续渲染进 DOM）。
   * 200ms 让重试足够密（用户感知是「秒到」），又不至于在长会话里空转太多轮。
   */
  SEARCH_SCROLL_RETRY_INTERVAL_MS: 200,

  /**
   * 搜索命中项高亮闪烁的保持时长：闪一下 4s 后移除高亮，让用户看清落点又不长期留痕。
   * 属于纯视觉反馈时长，改大只是闪更久（无功能影响），但仍会改变观感。
   */
  SEARCH_HIGHLIGHT_FLASH_MS: 4000,

  /**
   * 「加载全部」遮罩在加载结束后自动退场的延时（此时仍可能继续加载下一批）。
   * 2000ms 让用户看清遮罩上的完成信息，再自行消失；调短会闪一下就没。
   */
  LOAD_ALL_OVERLAY_AUTO_HIDE_MS: 2000,

  /**
   * 全部消息加载完成后，「刚完成」状态与遮罩一起保留多久再复位。
   * 1000ms 与上一条（2000ms）是两个独立计时器：这条走「全部加载完毕」的收尾路径。
   */
  LOAD_ALL_FINISHED_STATE_RESET_MS: 1000,

  /**
   * 渲染故障探测的「布局稳定」观察窗口：只有在助手中止、无会话加载、列表有内容时，
   * 才在 800ms 无二次渲染后判定布局异常。窗口太短会把流式输出的中间态误判为故障。
   */
  LAYOUT_STABILITY_PROBE_MS: 800,

  /**
   * 实时任务耗时显示的刷新节拍：每秒重取一次 Date.now() 驱动秒表。
   * 1s 是这类「已运行 12s」文案的自然粒度，再密只是无意义的重复渲染。
   */
  LIVE_ELAPSED_TICK_MS: 1000,

  // ===== 会话状态轮询与重试 =====

  /**
   * 兜底存活探测间隔：turn 开始/结束已有 stream_end / complete 事件驱动，这里只补齐中断按钮等状态。
   * 5000ms 是刻意放大的值——1.2s 级 session-status 帧会触发消费方整树重渲染，别再调小。
   */
  SESSION_STATUS_POLL_INTERVAL_MS: 5000,

  /**
   * check-session-status 返回「无法确认网关活动」（未知态）后，隔多久补探一次。
   * 1200ms 短于兜底轮询间隔：未知态是瞬时的，需要尽快收敛出确定结论，但又不打满请求。
   */
  SESSION_STATUS_UNKNOWN_RETRY_MS: 1200,

  /**
   * 进程退出且当前会话是「待建立」会话时，等多久再刷新项目列表。
   * 500ms 让服务端先把新会话落库/落盘，否则刷新到的项目列表里还没有这个会话。
   */
  SESSION_EXIT_PROJECT_REFRESH_MS: 500,

  /**
   * 会话权限授权请求的等待上限：超过即判定失败并回退 UI（不无限挂起）。
   * 10_000ms 给用户留出阅读确认弹窗的时间，同时保证断线时不至于长时间卡在等待态。
   */
  PERMISSION_GRANT_TIMEOUT_MS: 10_000,

  // ===== 瞬时反馈：复制 / 保存 / 横幅 =====

  /**
   * 复制成功反馈（按钮文案或状态变成「已复制」）保持多久后复位。
   * 2000ms 足够用户读到一个短确认，又不至于让按钮长时间停在「已复制」误导下一次操作。
   */
  COPY_FEEDBACK_RESET_MS: 2000,

  /**
   * 样式 JSON 的复制成功反馈复位延时。
   * 与 COPY_FEEDBACK_RESET_MS 是同一类反馈，但当前取值就是 1500ms（比通用值短一档），
   * 本次重构守恒取值故独立成键；若要统一应作为单独的行为变更评审，别顺手合并。
   */
  STYLE_COPY_FEEDBACK_RESET_MS: 1500,

  /**
   * 编辑器「保存成功」标记的保持时长：保存请求成功后亮 2s 再熄灭。
   * 与复制反馈同为 2s 量级的短确认，但触发源不同（写盘 vs 剪贴板），故独立命名。
   */
  SAVE_SUCCESS_FEEDBACK_MS: 2000,

  /**
   * 设置页保存状态（已保存 / 保存失败）提示的自动清除延时。
   * 2000ms 覆盖一次「改设置 → 看到反馈」的完整视线停留，再长会显得页面卡在提示态。
   */
  SETTINGS_SAVE_STATUS_RESET_MS: 2000,

  /**
   * 隐私页导出/导入结果横幅的自动消失延时。
   * 4000ms 比普通保存提示长：这里承载的是导出文件路径/导入结论等需要读一句的信息。
   */
  PRIVACY_BANNER_AUTO_DISMISS_MS: 4000,

  // ===== 输入与交互防抖 =====

  /**
   * 技能搜索（clawhub）请求防抖：停止输入 350ms 后才发请求。
   * 350ms 是「打字停顿」与「结果及时」的折中，再短会在连打时打出多余请求。
   */
  SKILL_SEARCH_DEBOUNCE_MS: 350,

  /**
   * 工作区路径补全的防抖：停止输入 200ms 后才查文件系统。
   * 比网络防抖（350ms）短，因为补全是本地/低频操作，用户对下拉出现的延迟更敏感。
   */
  PATH_SUGGESTION_DEBOUNCE_MS: 200,

  /**
   * 配置（sati config）校验请求的防抖：停止编辑 400ms 后才提交校验。
   * 比技能搜索更长：校验会解析整份配置，连打时不值得每次都跑。
   */
  CONFIG_VALIDATION_DEBOUNCE_MS: 400,

  /**
   * 触摸结束后抑制合成 click 的窗口：移动端菜单在 touchend 里打开后，
   * 350ms 内到来的合成 click 会被吞掉，避免「一次触摸开两次菜单」。
   */
  TOUCH_TAP_CLICK_SUPPRESSION_MS: 350,

  /**
   * 文档预览（DOCX / PDF）里 selectionchange / mouseup 后的防抖：等选区稳定 40ms 再算浮层位置。
   * 40ms 只为合并同一手势内的连续 selectionchange 事件，不引入可感知延迟。
   */
  SELECTION_ACTION_DEBOUNCE_MS: 40,

  /**
   * Diff 视图首次挂载后，等 merge 装饰计算完再滚到第一个变更块。
   * 100ms 让 CodeMirror 的装饰落地、变更块位置稳定，否则会滚到错误行。
   */
  DIFF_CHUNK_SCROLL_SETTLE_MS: 100,

  // ===== 更新下载 / IM 集成 / 应用骨架 =====

  /**
   * 桌面端更新下载进度轮询间隔（REST 轮询下载状态，直到 downloaded / failed / cancelled）。
   * 1000ms 让进度条看起来连续，同时把每秒最多一次状态请求控制在可接受量级。
   */
  UPDATE_DOWNLOAD_POLL_INTERVAL_MS: 1000,

  /**
   * IM 通道（飞书 / 企业微信）扫码登录期间轮询二维码状态的间隔。
   * 3000ms 与扫码登录的真实变化速度匹配：放慢会明显滞后于用户扫码，加快只是空请求。
   */
  IM_QR_POLL_INTERVAL_MS: 3000,

  /**
   * 微信通道扫码轮询间隔。
   * 比飞书/企业微信（3000ms）短一档：微信侧 runtime 会自愈并换二维码，需要更快看到新码。
   */
  WEIXIN_QR_POLL_INTERVAL_MS: 2000,

  /**
   * 网关状态轮询间隔：仅在微信 runtime 处于 starting / waiting_for_login / expired 等瞬态时启用，
   * 用于观察扫码自愈（换新二维码）后的状态。3000ms 与 IM 二维码轮询同量级，属不同端点、不同关切。
   */
  GATEWAY_STATUS_POLL_INTERVAL_MS: 3000,

  /**
   * WebSocket 心跳（ping 帧）间隔：连接建立后每 30s 发一次，靠它探活并维持中间层不回收连接。
   * 30_000ms 是长连接心跳的常见量级，调小会成倍增加空帧，调大会让断链发现变慢。
   */
  WS_PING_INTERVAL_MS: 30_000,

  /**
   * 加载进度到达 complete 后，让完成态在 UI 上多停留多久再清除。
   * 500ms 避免「最后一帧进度瞬间消失」的闪烁，给用户一个「确实完成」的落点。
   */
  LOADING_PROGRESS_COMPLETE_HOLD_MS: 500,

  /**
   * 触发下载后延迟多久回收 Blob URL：太早收回会让部分浏览器来不及开始下载。
   * 1000ms 已足够点击落地，回收后释放内存，避免长会话里累积 object URL。
   */
  DOWNLOAD_BLOB_URL_REVOKE_MS: 1000,
} as const;
